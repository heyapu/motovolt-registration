import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const migration = readFileSync(new URL('../supabase/migrations/202611090002_finance_options.sql', import.meta.url), 'utf8');
test('finance settings default off for upcoming partners; protect history and reject disabled/unknown partners', async () => {
    const db = new PGlite();
    await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
 create table form_registrations(id integer primary key,payment_mode text,financer_name text);
 insert into form_registrations values(1,'finance','Historical Bank');
 create function dashboard_validate_session(p_hash text) returns jsonb language sql as $$select case when p_hash='valid-test-session' then '{}'::jsonb end$$;`);
    await db.exec(migration);
    const rows = async (sql: string, args: unknown[] = []) => (await db.query<any>(sql, args)).rows;
    assert.deepEqual((await rows('select name from registration_financers where active order by sort_order')).map(r => r.name), ['Bajaj Fin LTD', 'BFL Wheels HS']);
    assert.equal((await rows('select count(*)::int n from registration_financers where not active'))[0].n, 4);
    assert.equal((await rows('select financer_name from form_registrations where id=1'))[0].financer_name, 'Historical Bank');
    await db.exec("insert into form_registrations values(2,'finance','Bajaj Fin LTD')");
    await assert.rejects(db.exec("insert into form_registrations values(3,'finance','IDFC')"), /INVALID_INPUT/);
    await assert.rejects(db.exec("insert into form_registrations values(3,'finance','Typed Bank')"), /INVALID_INPUT/);
    await assert.rejects(db.exec("insert into form_registrations values(3,'finance',null)"), /INVALID_INPUT/);
    await assert.rejects(db.query('select dashboard_set_financer($1,$2,$3)', ['bad', 'idfc', true]), /DASHBOARD_UNAUTHORIZED/);
    await db.query('select dashboard_set_financer($1,$2,$3)', ['valid-test-session', 'idfc', true]);
    await db.exec("insert into form_registrations values(3,'finance','IDFC')");
    await db.query('select dashboard_set_financer($1,$2,$3)', ['valid-test-session', 'bajaj_fin_ltd', false]);
    await assert.rejects(db.exec("insert into form_registrations values(4,'finance','Bajaj Fin LTD')"), /INVALID_INPUT/);
    assert.equal((await rows('select financer_name from form_registrations where id=2'))[0].financer_name, 'Bajaj Fin LTD');
    await db.exec("insert into form_registrations values(4,'cash','Ignore this')");
    assert.equal((await rows('select financer_name from form_registrations where id=4'))[0].financer_name, null);
    await db.exec(migration);
    assert.equal((await rows("select active from registration_financers where id='idfc'"))[0].active, true);
    assert.equal((await rows("select active from registration_financers where id='bajaj_fin_ltd'"))[0].active, false);
    await db.exec('set role anon');
    await assert.rejects(db.exec('select * from registration_financers'), /permission denied/);
    await assert.rejects(db.query('select dashboard_financers($1)', ['valid-test-session']), /permission denied/);
    await db.exec('reset role');
    await db.close();
});
